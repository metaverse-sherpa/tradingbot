    Column('alpaca_endpoint', String),
    Column('alpaca_start_equity', Float),
    Column('premium_referrals', Integer, default=0),
    Column('premium_expired_notified', Boolean, default=False),
    Column('had_premium_before', Boolean, default=False),
    Column('referral_reward_triggered', Boolean, default=False),
    Column('bingx_futures_type', String, default='standard'),
    Column('coinbase_sandbox', Integer, default=1),
