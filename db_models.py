    Column('strategy', String, default='Valkyrie Elite Scalper'),
    Column('active_crypto_strategy', String, default='Valkyrie Elite Scalper'),
    Column('active_stock_strategy', String, default='None'),
    Column('risk_pct', Float, default=1.0),
    Column('stock_risk_pct', Float, default=2.0),
    Column('enabled_symbols', String),
    Column('referred_by', Integer),
    Column('premium_expiry', Integer, default=0),
    Column('referral_count', Integer, default=0),
    Column('has_open_positions', Boolean, default=False),
    Column('undercover_mode', Boolean, default=False),
    Column('source_wallet', String),
    Column('last_audit_stats', String),
    Column('referral_credits', Float, default=0.0),
    Column('full_name', String),
    Column('username', String),
